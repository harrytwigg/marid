/**
 * Turns Phosphor's SVG sources into one React module per icon: duotone, except
 * the names `icon-map.mjs` lists in `WEIGHT_OVERRIDES`, which use another weight.
 *
 *   node scripts/generate-icons.mjs          write src/components/ui/icons/
 *   node scripts/generate-icons.mjs --check  fail if the checked-in output is stale
 *
 * `@phosphor-icons/react` carries all six weights inside every icon, so a
 * route that draws one glyph downloads six. Each duotone source here is two
 * paths (a regular one, a single path), so a generated module carries those
 * strings and nothing else.
 * The output is checked in; this script is the only thing that writes it.
 */
import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

import { ICON_MAP, WEIGHT_OVERRIDES } from "./icon-map.mjs"

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const outDir = path.join(packageRoot, "src", "components", "ui", "icons")
// The package's `exports` hides its own package.json, so the SVGs are found
// from the install path instead of through the resolver.
const assetsDir = path.join(packageRoot, "node_modules", "@phosphor-icons", "core", "assets")

const HEADER = "// Generated by scripts/generate-icons.mjs from @phosphor-icons/core. Do not edit.\n"

/** The source file of a glyph: duotone files carry a suffix, regular ones do not. */
function sourceFile(slug, weight) {
  return weight === "regular"
    ? path.join(assetsDir, "regular", `${slug}.svg`)
    : path.join(assetsDir, "duotone", `${slug}-duotone.svg`)
}

/** The path of a regular source: the outline alone. */
export function parseRegular(svg, slug) {
  const paths = [...svg.matchAll(/<path\b([^>]*?)\/>/g)].map((match) => match[1])
  if (paths.length !== 1 || /\bopacity=/.test(paths[0])) throw new Error(`${slug}: expected one outline path`)
  return { line: paths[0].match(/\bd="([^"]+)"/)?.[1] }
}

/** The two paths of a duotone source: the 20% layer, then the outline. */
export function parseDuotone(svg, slug) {
  const paths = [...svg.matchAll(/<path\b([^>]*?)\/>/g)].map((match) => match[1])
  const d = (attrs) => attrs.match(/\bd="([^"]+)"/)?.[1]
  const [layer, line, ...rest] = paths
  const isLayer = layer !== undefined && /\bopacity="0\.2"/.test(layer)
  if (!isLayer || line === undefined || rest.length > 0 || /\bopacity=/.test(line)) {
    throw new Error(`${slug}: expected one 20% layer path and one outline path`)
  }
  return { layer: d(layer), line: d(line) }
}

