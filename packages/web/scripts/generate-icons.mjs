/** @param {string} name @param {{ layer?: string, line: string }} glyph */
function moduleSource(name, { layer, line }) {
  const layerProp = layer === undefined ? "" : ` layer="${layer}"`
  return (
    HEADER +
    `import { IconSvg, type IconProps } from "../icon-svg"\n\n` +
    `export function ${name}(props: IconProps) {\n` +
    `  return <IconSvg name="${name}"${layerProp} line="${line}" {...props} />\n` +
    `}\n`
  )
}

function barrelSource(names) {
  return HEADER + names.map((name) => `export { ${name} } from "./${name}"\n`).join("")
}

/** Every file the generator owns, as filename -> contents. */
export async function buildOutput() {
  const names = Object.keys(ICON_MAP).sort()
  const files = new Map()
  for (const name of names) {
    const slug = ICON_MAP[name]
    const weight = WEIGHT_OVERRIDES[name] ?? "duotone"
    const svg = await readFile(sourceFile(slug, weight), "utf8").catch(() => {
      throw new Error(`${name}: no ${weight} glyph "${slug}" in @phosphor-icons/core`)
    })
    const parse = weight === "regular" ? parseRegular : parseDuotone
    files.set(`${name}.tsx`, moduleSource(name, parse(svg, slug)))
  }
  files.set("index.ts", barrelSource(names))
  files.set("NOTICE.md", NOTICE)
  return files
}

async function existing() {
  const names = await readdir(outDir).catch(() => [])
  return new Map(await Promise.all(names.map(async (n) => /** @type {[string, string]} */ ([n, await readFile(path.join(outDir, n), "utf8")]))))
}

function staleFiles(wanted, have) {
  const stale = [...wanted].filter(([name, text]) => have.get(name) !== text).map(([name]) => name)
  return [...stale, ...[...have.keys()].filter((name) => !wanted.has(name))]
}

async function main(check) {
  const wanted = await buildOutput()
  const have = await existing()
  const stale = staleFiles(wanted, have)
  if (check) {
    if (stale.length === 0) return
    console.error(`Generated icons are stale (${stale.join(", ")}). Run: pnpm --filter @jinn/web icons`)
    process.exitCode = 1
    return
  }
  await rm(outDir, { recursive: true, force: true })
  await mkdir(outDir, { recursive: true })
  await Promise.all([...wanted].map(([name, text]) => writeFile(path.join(outDir, name), text)))
  console.log(`Wrote ${wanted.size - 2} icons to ${path.relative(packageRoot, outDir)}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main(process.argv.includes("--check"))
